const SCROLL_THUMB_MIN_HEIGHT = 32

function SidebarContent({
  className,
  children,
  ...props
}: React.ComponentProps<"div">) {
  const viewportRef = React.useRef<HTMLDivElement>(null)
  const contentRef = React.useRef<HTMLDivElement>(null)
  const thumbRef = React.useRef<HTMLDivElement>(null)
  const [thumb, setThumb] = React.useState<{
    top: number
    height: number
  } | null>(null)
  const [dragging, setDragging] = React.useState(false)
  const dragCleanupRef = React.useRef<(() => void) | null>(null)

  const updateThumb = React.useCallback(() => {
    const viewport = viewportRef.current
    if (!viewport) return
    const { scrollTop, scrollHeight, clientHeight } = viewport
    // Hide the thumb when there's nothing to scroll, or when the viewport is
    // too short to fit even the minimum thumb (maxTop would be <= 0 and the
    // drag math would divide by zero or invert).
    if (
      scrollHeight <= clientHeight + 1 ||
      clientHeight <= SCROLL_THUMB_MIN_HEIGHT
    ) {
      setThumb(null)
      return
    }
    const height = Math.max(
      (clientHeight / scrollHeight) * clientHeight,
      SCROLL_THUMB_MIN_HEIGHT
    )
    const maxTop = clientHeight - height
    const top = (scrollTop / (scrollHeight - clientHeight)) * maxTop
    setThumb({ top, height })
  }, [])

  React.useEffect(() => {
    updateThumb()
    const viewport = viewportRef.current
    const content = contentRef.current
    if (!viewport || !content) return
    const observer = new ResizeObserver(updateThumb)
    observer.observe(viewport)
    observer.observe(content)
    return () => observer.disconnect()
  }, [updateThumb])

  const handleTrackPointerDown = (event: React.PointerEvent<HTMLDivElement>) => {
    const viewport = viewportRef.current
    if (!viewport || !thumb || event.button !== 0) return
    event.preventDefault()

    const scrollable = viewport.scrollHeight - viewport.clientHeight
    const maxTop = viewport.clientHeight - thumb.height
    if (scrollable <= 0 || maxTop <= 0) return
    let startScrollTop = viewport.scrollTop

    // Clicking the track (not the thumb) jumps so the thumb centers there,
    // then transitions straight into a drag.
    if (event.target !== thumbRef.current) {
      const trackY =
        event.clientY - event.currentTarget.getBoundingClientRect().top
      const targetTop = Math.min(
        Math.max(trackY - thumb.height / 2, 0),
        maxTop
      )
      startScrollTop = (targetTop / maxTop) * scrollable
      viewport.scrollTop = startScrollTop
    }

    const startY = event.clientY
    setDragging(true)
    const previousCursor = document.body.style.cursor
    document.body.style.cursor = "grabbing"

    const handleMove = (moveEvent: PointerEvent) => {
      viewport.scrollTop =
        startScrollTop + ((moveEvent.clientY - startY) / maxTop) * scrollable
    }
    const handleUp = () => {
      setDragging(false)
      document.body.style.cursor = previousCursor
      window.removeEventListener("pointermove", handleMove)
      window.removeEventListener("pointerup", handleUp)
      dragCleanupRef.current = null
    }
    window.addEventListener("pointermove", handleMove)
    window.addEventListener("pointerup", handleUp)
    dragCleanupRef.current = handleUp
  }

  // If the component unmounts mid-drag, tear down the window listeners and
  // restore the body cursor.
  React.useEffect(() => {
    return () => dragCleanupRef.current?.()
  }, [])

  return (
    <div
      data-slot="sidebar-content"
      data-sidebar="content"
      className={cn("relative min-h-0 flex-1", className)}
      {...props}
    >
      <div
        ref={viewportRef}
        onScroll={updateThumb}
        className="sidebar-scroll h-full overflow-y-auto group-data-[collapsible=icon]:overflow-x-hidden"
      >
        <div ref={contentRef} className="flex flex-col gap-2">
          {children}
        </div>
      </div>
      {thumb && (
        <div
          onPointerDown={handleTrackPointerDown}
          className={cn(
            "absolute inset-y-0 right-0 w-2.5 cursor-grab transition-[right] duration-200 ease-linear group-data-[collapsible=icon]:w-1.5",
            // In the inset variant the wrapper and the rail share bg-sidebar,
            // so the rail's own right edge is invisible. When collapsed, the
            // rail is (icon + 2px) wide inside a p-2 container and the main
            // panel adds ml-2, leaving a spacing(4) - 2px gap. Push the track
            // across that gap so the thumb sits flush against the main panel.
            "group-data-[variant=inset]:group-data-[collapsible=icon]:right-[calc(2px-(--spacing(4)))]"
          )}
        >
          <div
            ref={thumbRef}
            style={{ top: thumb.top, height: thumb.height }}
            className={cn(
              "absolute right-0 rounded-full transition-[width,background-color] duration-150",
              dragging
                ? "w-1.5 bg-sidebar-foreground/40"
                : "w-1 bg-sidebar-foreground/15 hover:w-1.5 hover:bg-sidebar-foreground/30"
            )}
          />
        </div>
      )}
    </div>
  )
}

